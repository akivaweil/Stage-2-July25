#include <Stage2_Machine.h>

//* ************************************************************************
//* ************************ ALIGNMENT STATE ****************************
//* ************************************************************************
// This state extends the alignment cylinder to align the workpiece

void handleAlignmentState() {
    //! ************************************************************************
    //! STEP 1: EXTEND ALIGNMENT CYLINDER
    //! ************************************************************************
    extendAlignmentCylinder();
    
    //! ************************************************************************
    //! STEP 2: WAIT FOR ALIGNMENT TO SETTLE
    //! ************************************************************************
    delay(Motion::ALIGN_SETTLE_TIME);
    
    //! ************************************************************************
    //! STEP 3: PROCEED TO CUTTING CYCLE
    //! ************************************************************************
    currentState = CUTTING_CYCLE;
} 